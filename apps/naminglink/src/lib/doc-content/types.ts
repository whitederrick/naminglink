/**
 * 편집 문서(안내·소개·공지·문의)의 자료형.
 *
 * ## 왜 본문을 JSX에서 꺼내는가
 *
 * 이 문서들은 본문이 각 `page.tsx`의 JSX에 박혀 있었고, 그래서 **번역 파이프라인이 지나갈 수
 * 없었다.** 화면 사전과 약관은 23로케일인데 이 층만 ko/en 두 벌로 남았고, 2026-08-08에
 * 서치 콘솔이 그 자리를 정확히 짚었다 — 「중복 페이지」 53건이 전부 `/{언어}/guide/*`·
 * `/about`·`/notice`였다. 번역이 없는 문서를 23개 언어 주소로 내보내고 있었기 때문이다.
 *
 * 잎(문자열)만 갈아 끼울 수 있게 구조를 자료로 바꾼다. 사주링크의 `translate-i18n.ts`와 같은
 * 방식이다 — **구조를 복사하고 문자열만 번역**하므로 키·중첩·배열 길이가 어긋날 자리가 없다.
 *
 * ## 서식은 자료에 담되, 그리는 자리를 함께 둔다
 *
 * 굵게와 링크가 본문에 필요하다. 그렇다고 HTML을 문자열로 넣으면 번역기가 태그를 망가뜨리고
 * 검사할 방법도 없어진다. 그래서 표기를 둘로 좁혔다:
 *
 *     **굵게**            → <b>
 *     [보이는 말](/경로)   → 로케일이 붙은 내부 링크
 *
 * **표기를 늘리지 말 것.** 표기를 하나 늘릴 때마다 번역기가 깨뜨릴 자리가 하나 늘고, 그것을
 * 세는 검사기도 함께 늘어야 한다. 이 둘로 안 되는 문서가 나오면 표기를 늘리기 전에 그 문서가
 * 정말 편집 문서인지부터 볼 것 — 표·통계는 `GuideStats`처럼 자기 부품이 따로 있다.
 *
 * 링크 경로는 **로케일을 붙이지 않은 채로 적는다**(`/contact`). 그리는 쪽이 `localePath`로
 * 붙인다 — 자료에 `/ja/contact`를 적으면 그 문장은 일본어판에서만 맞는 말이 된다.
 *
 * ## 사업자 정보는 자리표시자로 (`{email}`)
 *
 * 문의 화면은 상호·대표자·이메일 같은 값을 적어야 하는데, **그 값을 문장에 박아 두면 안 된다.**
 * 관리자 화면에서 주소나 연락처를 바꿨을 때 그 문서만 옛 값으로 남고, 표시와 실제가 어긋나는
 * 것은 법이 금하는 것이다. 더 나쁜 경우도 이미 겪었다 — 약관에 값을 박아 두었더니 **번역기가
 * 대표자 이름을 언어마다 다른 한자로 지어냈다**(`郭恩河`/`郭恩哈`, 2026-08-07).
 *
 * 그래서 값은 `{email}`처럼 자리표시자로 적고 그리는 쪽이 채운다. 번역기는 이 표기를 그대로
 * 옮겨야 하고(약관 번역기와 같은 규칙), 검사기가 로케일 사이에 **개수가 같은지** 센다.
 */

/**
 * 문단·목록·숫자판.
 *
 * `stats`는 자료에서 읽은 숫자를 눈에 띄게 놓는 자리다(`GuideStats`). **값을 여기 적지
 * 않는다** — `"{avoidTotal}자"`처럼 자리표시자로 두고 화면이 DB에서 읽어 채운다. 표가
 * 갱신되면 글의 숫자도 함께 바뀌어야 하기 때문이다.
 *
 * **자리표시자를 채우지 못한 블록은 그리지 않는다**(`DocBody`). 자료 조회가 실패했을 때
 * 화면에 `{avoidTotal}`이 그대로 나가는 것보다, 그 문단이 빠지는 편이 낫다 — 옮기기 전 코드도
 * `counts ? … : null`로 같은 판단을 하고 있었다.
 */
export type DocBlock =
  | { p: string }
  | { ul: string[] }
  | { stats: Array<{ value: string; label: string }> }
  /**
   * 그림. **자료에는 이름만 두고 그리는 것은 `DocBody`가 한다.**
   *
   * SVG 를 문자열로 자료에 넣으면 번역기가 그 안의 좌표와 태그를 건드린다. 이름만 두면 옮길
   * 것은 설명(`caption`) 하나뿐이고, 아는 이름이 아니면 아무것도 그려지지 않아 눈에 띈다.
   */
  | { figure: DocFigure; caption: string };

/** 그릴 수 있는 그림. 늘릴 때는 `DocBody`의 표에 함께 더한다. */
export type DocFigure = "hanja-match-flow" | "five-elements";

/**
 * 문서의 한 절.
 *
 * `kind: "note"`는 본문 중간의 강조 상자(`GuideNote`)다. 근거·출처처럼 따로 떼어 두면 좋은
 * 것에 쓰고, 제목은 없어도 된다.
 */
export type DocSection = {
  kind?: "section" | "note";
  title?: string;
  blocks: DocBlock[];
  /**
   * 화면이 이 절 끝에 끼워 넣을 것의 이름.
   *
   * **자료로 만들 수 없는 것이 있다.** 인명용 한자 목록의 초성 단추들처럼 눌러서 넘어가는
   * 것, 자료에서 읽어 그리는 표가 그렇다. 그런 자리는 이름만 두고 화면이 넘긴다
   * (`DocBody`의 `slots`). 자료에는 글만 남고, 글은 번역되고, 대화형 부분은 화면에 남는다.
   */
  slot?: string;
};

/**
 * 문서 한 편.
 *
 * `title`·`summary`는 **화면과 메타데이터가 함께 쓴다.** 두 곳에 따로 적으면 검색 결과에 나오는
 * 말과 화면에 보이는 말이 어긋난다.
 */
/**
 * 공지 화면의 글.
 *
 * **메타데이터는 여기 없다** — 올린 날·적용일·종류는 `lib/notices.ts`가 갖는다. 날짜를 로케일
 * 파일에 두면 스물세 벌이 서로 어긋날 수 있고, 어긋난 날짜는 이용 조건을 알린 시점을 다투게
 * 만든다. 여기 있는 것은 **읽는 글**뿐이고, 공지 본문은 `items`에 **공지 id로** 붙는다.
 */
export type NoticeCopy = {
  /** 종류 꼬리표. 키는 `NoticeKind`와 같아야 한다 — 화면이 그 값으로 찾는다. */
  kindLabels: { service: string; product: string; policy: string; support: string };
  /** 머리의 강조 상자. 여기에 무엇을 적고 무엇을 안 적는지 밝힌다. */
  intro: string;
  /** 공지가 하나도 없을 때. 지금은 안 보이지만 비는 날이 온다. */
  empty: { title: string; body: string };
  /** 적용일 표시. `{date}`가 실제 날짜로 바뀐다. */
  effective: string;
  /** 페이지 넘김. 공지가 열한 개가 되는 날 화면에 나타난다. */
  pager: { label: string; newer: string; older: string };
  /** 공지 본문. 키는 `notices.ts`의 `id`다. */
  items: Record<string, { title: string; body: string[] }>;
};

export type DocPage = {
  /** 히어로 위의 짧은 꼬리표 */
  eyebrow: string;
  title: string;
  summary: string;
  /** 돌아가기 버튼에 적을 말. 경로는 화면이 정한다(안내 허브인지 처음인지 다르다). */
  backLabel: string;
  sections: DocSection[];
};
