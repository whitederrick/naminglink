/**
 * 리포트 PDF의 장수. **고시에 적는 값이자 실제로 나가는 값이다.**
 *
 * ## 왜 상수로 두는가
 *
 * 이 숫자는 네 곳이 함께 봐야 한다 — 문서를 그리는 곳(선언된 `<Page>` 수), 장수를 재는 곳
 * (`scripts/render-report-scripts.tsx`), **고시하는 곳**(약관·안내 문서), 그리고 그 둘을 대조하는
 * 검사기(`scripts/verify-product-consistency.ts`). 네 곳이 각자 숫자를 적고 있으면 문서를 한 장
 * 늘렸을 때 나머지가 조용히 옛 값으로 남는다.
 *
 * ## 이 파일이 없어서 무슨 일이 있었나 (2026-08-07)
 *
 * 사주링크·드림링크에는 같은 상수가 있는데 **인연링크에만 없었다.** 그 결과:
 *
 * - 견본 렌더러가 **장수를 아예 안 셌다**(형제 앱 둘은 센다)
 * - 검사기가 고시의 「N장」을 **목차 줄 수**와 대조했다. 그 둘이 우연히 같던 동안만 맞는 검사다
 * - 그래서 **궁합 리포트 절반이 8장으로 나가고 있었다** — 약관은 7장이라고 적은 채로.
 *   라틴 문자 로케일에서 십신 표가 한 행 넘쳐 계산 근거가 다음 장으로 밀렸다(de·en·es·fil…).
 *   인연의 결도 36개 문서가 5장이었다(고시는 4장).
 *
 * ## 바꾸는 순서
 *
 * 1. 렌더러에서 `<Page>`를 더하거나 뺀다
 * 2. 이 값을 그에 맞게 고친다
 * 3. `render-report-scripts`를 **전 로케일**로 돌려 실제로 그 수가 나오는지 본다
 * 4. 약관·안내 문서의 장수 표기를 고친다
 *
 * 3번을 건너뛰지 말 것 — 지면이 깨지는 것은 글자가 다른 언어에서다.
 */

/** 사주 궁합 리포트. */
export const COMPATIBILITY_PAGE_COUNT = 7;

/** 인연의 결 리포트. */
export const AFFINITY_PAGE_COUNT = 4;
